#!/usr/bin/env python3
"""Generate numbers.typ from results/results.json. Nothing hand-typed.

Run after emit_results.py. Every figure the paper prints comes from here, so a
re-run of the pipeline cannot leave a stale statistic in the prose.
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
RES = json.load(open(os.path.join(HERE, "results", "results.json")))
OUT = os.path.join(HERE, "paper", "numbers.typ")
os.makedirs(os.path.dirname(OUT), exist_ok=True)

L = ["// GENERATED by emit_numbers.py from results/results.json — do not edit by hand.",
     "// Every statistic quoted in the paper is defined here, so nothing is transcribed.",
     ""]


def s(name, val):
    L.append(f'#let {name} = "{val}"')


def signed(x):
    return f"{x:+.1f}"


def ci(pair):
    return f"[{pair[0]:+.1f}, {pair[1]:+.1f}]"


s("generated", RES["generated_utc"])
s("bootreps", f'{RES["bootstrap_reps"]:,}')
s("bootseed", RES["bootstrap_seed"])
L.append("")

SHORT = {"gpqa_diamond": "g", "ifbench": "if", "lcb_v6": "lcb"}
for bench, e in RES["benchmarks"].items():
    p = SHORT[bench]
    L.append(f"// --- {e['label']} ---")
    s(f"{p}n", e["n_ids"])
    for arm, key in (("base", "base"), ("Bcc_0.1", "edit"), ("Rcc_0.1", "ctrl")):
        s(f"{p}acc{key}", f'{e["acc"][arm]:.1f}')
    for pair, key in (("base_to_edit", "be"), ("ctrl_to_edit", "ce"), ("base_to_ctrl", "bc")):
        v = e["paired"][pair]
        s(f"{p}d{key}", signed(v["delta"]))
        s(f"{p}ci{key}", ci(v["ci"]))
        s(f"{p}ci{key}lo", f'{v["ci"][0]:+.1f}')
        s(f"{p}ci{key}hi", f'{v["ci"][1]:+.1f}')
        s(f"{p}better{key}", v["better"])
        s(f"{p}worse{key}", v["worse"])
    t = e.get("tokens")
    if t:
        for arm, key in (("base", "base"), ("Bcc_0.1", "edit"), ("Rcc_0.1", "ctrl")):
            s(f"{p}tok{key}", f'{t["mean"][arm]:,.0f}')
            s(f"{p}trunc{key}", t["trunc"][arm])
        for pair, key in (("base_to_edit", "be"), ("ctrl_to_edit", "ce"), ("base_to_ctrl", "bc")):
            v = t[pair]
            s(f"{p}tokpct{key}", f'{v["pct"]:+.1f}')
            s(f"{p}tokci{key}", ci(v["ci"]))
    L.append("")

# Census: the avg@4 contamination, stated in numbers rather than prose.
L.append("// --- GPQA sample census (avg@4 contamination) ---")
for arm, key in (("base", "base"), ("Bcc_0.1", "edit"), ("Rcc_0.1", "ctrl")):
    c = RES["census"][arm]
    s(f"cens{key}unf", c["rows_unfiltered"])
    s(f"cens{key}fil", c["rows_filtered"])
L.append("")

with open(OUT, "w") as f:
    f.write("\n".join(L) + "\n")

print(f"wrote {OUT} ({len(L)} lines, {sum(1 for x in L if x.startswith('#let'))} constants)")
